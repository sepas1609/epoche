/**
 * Rebuttal Document Generator
 * Compiles team responses into publication-standard LaTeX, Markdown, and formatted HTML.
 */

export class RebuttalGenerator {
  /**
   * Group comments by reviewer name
   */
  static groupByReviewer(comments) {
    const groups = {};
    comments.forEach(c => {
      const r = c.reviewer || "General Remarks";
      if (!groups[r]) groups[r] = [];
      groups[r].push(c);
    });
    return groups;
  }

  /**
   * Generate LaTeX formatted response document
   */
  static toLaTeX(paper, comments) {
    const groups = this.groupByReviewer(comments);
    let tex = `% =========================================================================
% Point-by-Point Response to Reviewers
% Generated by Epoché (https://github.com/saranboddu/epoche)
% =========================================================================
\\documentclass[11pt,a4paper]{article}
\\usepackage[utf8]{inputenc}
\\usepackage{geometry}
\\geometry{margin=1in}
\\usepackage{xcolor}
\\usepackage{titlesec}
\\usepackage{tcolorbox}
\\usepackage{hyperref}

\\definecolor{rebuttalblue}{RGB}{14, 116, 144}
\\definecolor{quoteframe}{RGB}{203, 213, 225}

\\title{\\textbf{Response to Reviewers' Comments}\\\\
\\large Manuscript ID: \\texttt{${paper.trackingId || 'N/A'}}\\\\
``${paper.title}''}
\\author{${paper.authors.map(a => a.name).join(', ')}}
\\date{\\today}

\\begin{document}
\\maketitle

\\noindent We sincerely thank the Editor and the Reviewers for their constructive feedback and encouraging remarks. Below, we provide detailed point-by-point responses addressing all reviewer comments.

\\vspace{1em}
`;

    for (const [reviewer, list] of Object.entries(groups)) {
      tex += `\\section*{Response to ${reviewer}}\n\n`;
      list.forEach((c, idx) => {
        tex += `\\subsection*{Comment ${c.point || idx + 1}}
\\begin{tcolorbox}[colback=gray!5,colframe=quoteframe,title={\\small\\textbf{Reviewer Comment:}}]
\\textit{``${c.quote.replace(/"/g, "''")}''}
\\end{tcolorbox}

\\noindent\\textbf{Author Response:}\\\\
${c.response || 'In response...'}

\\vspace{0.8em}
\\noindent\\textbf{Changes in Revised Manuscript:}\\\\
\\textcolor{rebuttalblue}{\\textit{${c.manuscriptChange || 'Updated in revised manuscript.'}}}

\\vspace{1.5em}
`;
      });
    }

    tex += `\\end{document}\n`;
    return tex;
  }

  /**
   * Generate Markdown response
   */
  static toMarkdown(paper, comments) {
    const groups = this.groupByReviewer(comments);
    let md = `# Response to Reviewers' Comments\n\n`;
    md += `**Manuscript Title:** ${paper.title}  \n`;
    md += `**Tracking ID:** \`${paper.trackingId || 'N/A'}\`  \n`;
    md += `**Journal:** ${paper.journal}  \n`;
    md += `**Authors:** ${paper.authors.map(a => a.name).join(', ')}  \n\n`;
    md += `--- \n\n`;

    for (const [reviewer, list] of Object.entries(groups)) {
      md += `## Response to ${reviewer}\n\n`;
      list.forEach((c, idx) => {
        md += `### Comment ${c.point || idx + 1}\n\n`;
        md += `> **Reviewer Remark:**  \n> "${c.quote}"\n\n`;
        md += `**Author Response:**  \n${c.response || 'In response...'}\n\n`;
        md += `**Manuscript Revision:**  \n_${c.manuscriptChange || 'Updated in revised manuscript.'}_\n\n`;
        md += `---\n\n`;
      });
    }

    return md;
  }

  /**
   * Generate academic HTML preview
   */
  static toHTMLPreview(paper, comments) {
    const groups = this.groupByReviewer(comments);
    let html = `
      <div style="font-family: 'Times New Roman', Times, serif; line-height: 1.6; color: #111;">
        <div style="text-align: center; margin-bottom: 25px; border-bottom: 2px solid #333; padding-bottom: 15px;">
          <h2 style="margin: 0 0 8px 0; font-size: 20px;">POINT-BY-POINT RESPONSE TO REVIEWERS</h2>
          <p style="margin: 4px 0; font-weight: bold;">${paper.title}</p>
          <p style="margin: 4px 0; font-size: 13px; color: #555;">Manuscript Tracking ID: <strong>${paper.trackingId || 'N/A'}</strong> | Target Journal: <strong>${paper.journal}</strong></p>
          <p style="margin: 4px 0; font-size: 13px;">${paper.authors.map(a => a.name).join(', ')}</p>
        </div>
        <p>Dear Editor and Reviewers,</p>
        <p>We extend our deepest gratitude for the thorough evaluation of our manuscript. All reviewer suggestions have been comprehensively addressed as detailed below.</p>
    `;

    for (const [reviewer, list] of Object.entries(groups)) {
      html += `<h3 style="margin-top: 25px; border-bottom: 1px solid #777; padding-bottom: 4px; color: #0f172a;">${reviewer}</h3>`;
      list.forEach((c, idx) => {
        html += `
          <div style="margin: 18px 0; padding: 12px 16px; background: #f8fafc; border-left: 4px solid #0284c7; border-radius: 4px;">
            <p style="margin: 0 0 8px 0; font-weight: bold; color: #334155;">Comment ${c.point || idx + 1}:</p>
            <blockquote style="margin: 0 0 10px 0; font-style: italic; color: #1e293b;">"${c.quote}"</blockquote>
            <p style="margin: 8px 0 4px 0; font-weight: bold; color: #0f172a;">Response:</p>
            <p style="margin: 0 0 8px 0;">${c.response || 'In response...'}</p>
            <p style="margin: 8px 0 2px 0; font-weight: bold; color: #0284c7;">Changes in Revised Manuscript:</p>
            <p style="margin: 0; font-style: italic; color: #0369a1;">${c.manuscriptChange || 'Updated in manuscript.'}</p>
          </div>
        `;
      });
    }

    html += `</div>`;
    return html;
  }
}
